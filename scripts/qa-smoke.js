async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.reload();
  await page.locator('[data-action="new"]').click();
  await page.locator('[data-action="confirm-new"]').click();
  await page.getByRole('button', { name: '点灯营业' }).click();
  const start = await page.evaluate(() => window.nightMarketDiagnostics());
  await page.locator('[data-action="coin1"]').click();
  await page.keyboard.press('Enter');
  let after = await page.evaluate(() => window.nightMarketDiagnostics());
  check(JSON.stringify(start.state) === JSON.stringify(after.state), '错误找零改变了规则状态');
  check((await page.locator('#guide-bar').innerText()).includes('库存没有扣除'), '拒绝教学未推进');
  await page.locator('[data-action="note5"]').click();
  await page.locator('[data-action="coin1"]').click();
  await page.keyboard.down('Enter');
  await page.keyboard.down('Enter');
  after = await page.evaluate(() => window.nightMarketDiagnostics());
  check(after.state.cycle === 1 && after.state.served.length === 1, '长按回车造成重复提交');
  check(after.modal === 'tutorial', '合法提交未显示入账教学');
  await page.keyboard.up('Enter');
  await page.locator('[data-action="tutorial-reset"]').click();
  after = await page.evaluate(() => window.nightMarketDiagnostics());
  check(after.state.cycle === 0 && after.state.cash.ones === 2 && after.state.cash.fives === 1, '教学重置未回到相同初态');
  await page.locator('[data-action="coin1"]').click();
  await page.locator('#selected-money').click({ button: 'right' });
  after = await page.evaluate(() => window.nightMarketDiagnostics());
  check(after.draft.ones === 0 && after.state.cycle === 0, '右键取消草稿有副作用');
  await page.locator('[data-guest="night-01-guest-2"]').dragTo(page.locator('[data-guest="night-01-guest-1"]'));
  after = await page.evaluate(() => window.nightMarketDiagnostics());
  check(after.queueOrder[0] === 'night-01-guest-2' && after.state.cycle === 0, '拖拽未排序或推进了回合');
  await page.keyboard.press('Escape');
  const paused = await page.evaluate(() => window.nightMarketDiagnostics().state);
  await page.waitForTimeout(20000);
  check(JSON.stringify(paused) === JSON.stringify(await page.evaluate(() => window.nightMarketDiagnostics().state)), '暂停20秒后状态变化');
  await page.getByRole('button', { name: '继续营业', exact: true }).click();
  check((await page.evaluate(() => window.nightMarketDiagnostics().state.cycle)) === 0, '恢复导致误提交');
  const bounds = await page.evaluate(() => {
    const selectors = ['#submit', '#guide-bar', '#progress-strip', '#cash-items', '.queue-footer'];
    return selectors.map(selector => { const rect = document.querySelector(selector).getBoundingClientRect(); return { selector, top: rect.top, bottom: rect.bottom, right: rect.right, visible: rect.top >= 0 && rect.bottom <= innerHeight + 1 && rect.right <= innerWidth }; });
  });
  check(bounds.every(item => item.visible), `关键界面越界：${JSON.stringify(bounds)}`);
  await page.screenshot({ path: 'output/playwright/game-1280.png' });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByLabel('降低动态与闪烁').check();
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: '继续营业', exact: true }).click();
  check((await page.evaluate(() => window.nightMarketDiagnostics().progress.settings.reduceMotion)) === true, '设置没有保存');
  check((await page.evaluate(() => window.nightMarketDiagnostics().state.cycle)) === 0, '继续进度不正确');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByLabel('降低动态与闪烁').uncheck();
  await page.getByRole('button', { name: '完成', exact: true }).click();
  return { result: 'PASS', viewport: page.viewportSize(), checks: ['拒绝教学', '合法入账教学', '教学同态重置', '长按去重', '右键取消', '真实拖拽', '暂停20秒', '恢复无误提交', '1280关键控件可见', '设置与继续存档'], bounds };
}
